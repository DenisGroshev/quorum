package app.quorum.catalog;

import static org.assertj.core.api.Assertions.assertThat;

import app.quorum.catalog.domain.Genre;
import app.quorum.catalog.infra.CatalogGenreRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Testcontainers
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.NONE)
class GenreRepositoryIT {

    @Container
    static PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    @DynamicPropertySource
    static void properties(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", POSTGRES::getJdbcUrl);
        registry.add("spring.datasource.username", POSTGRES::getUsername);
        registry.add("spring.datasource.password", POSTGRES::getPassword);
        registry.add("TG_BOT_TOKEN", () -> "unused-in-this-test");
        registry.add("JWT_SECRET", () -> "integration-test-jwt-secret-should-be-long-enough");
        registry.add("TG_APP_NAME", () -> "quorum-it-tests");
        registry.add("TMDB_TOKEN", () -> "unused-in-this-test");
    }

    @Autowired
    private CatalogGenreRepository genreRepository;

    @Test
    void saveAndRead_roundTrips() {
        genreRepository.save(Genre.of(28, "Боевик", "Action"));

        Genre loaded = genreRepository.findById(28).orElseThrow();

        assertThat(loaded.getNameRu()).isEqualTo("Боевик");
        assertThat(loaded.getNameEn()).isEqualTo("Action");
    }

    @Test
    void id_isNeverAutoGenerated_theTmdbIdIsKeptAsIs() {
        // TMDB присылает genre_id не по порядку (например, 878 раньше 28) — если бы id
        // генерировался базой, сохранённая запись получила бы чужой id.
        genreRepository.save(Genre.of(878, "Фантастика", "Science Fiction"));

        Genre loaded = genreRepository.findById(878).orElseThrow();

        assertThat(loaded.getId()).isEqualTo(878);
    }
}
